ALTER TABLE copilot.conversation_change_outbox
    ADD COLUMN event_sequence bigint GENERATED BY DEFAULT AS IDENTITY;

WITH ordered_events AS (
    SELECT id,
           row_number() OVER (ORDER BY created_at, id)::bigint AS event_sequence
    FROM copilot.conversation_change_outbox
)
UPDATE copilot.conversation_change_outbox AS event
SET event_sequence = ordered_events.event_sequence
FROM ordered_events
WHERE event.id = ordered_events.id;

SELECT setval(
    pg_get_serial_sequence('copilot.conversation_change_outbox', 'event_sequence'),
    COALESCE(MAX(event_sequence), 1),
    COUNT(*) > 0)
FROM copilot.conversation_change_outbox;

CREATE UNIQUE INDEX ux_conversation_change_outbox_event_sequence
    ON copilot.conversation_change_outbox(event_sequence);

DROP INDEX IF EXISTS copilot.ix_conversation_change_outbox_scope_order;

CREATE INDEX ix_conversation_change_outbox_scope_sequence
    ON copilot.conversation_change_outbox(account_id, conversation_id, event_sequence);
